export default function Sidebar() {
  const pathname = usePathname()
  const router = useRouter()
  const { role } = useUser()

  async function handleLogout() {
    const supabase = getBrowserClient()
    await supabase.auth.signOut()
    router.push('/login')
    router.refresh()
  }

  const allItems = NAV_GROUPS.flatMap(group => group.items).filter(item => {
    if (item.superOnly && role !== 'super') return false
    if (item.hideNormal && role === 'normal') return false
    return true
  })

  return (
    <aside
      className="fixed inset-y-0 left-0 w-[220px] flex flex-col z-50"
      style={{ background: '#0f172a', borderRight: '1px solid rgba(255,255,255,0.05)' }}
    >
      {/* ── Logo ── */}
      <div className="px-5 pt-6 pb-5">
        <div className="flex items-center gap-2.5">
          <div
            className="w-8 h-8 rounded-lg flex items-center justify-center flex-shrink-0"
            style={{ background: 'linear-gradient(135deg, #16a34a, #15803d)', boxShadow: '0 4px 12px rgba(22,163,74,0.35)' }}
          >
            <svg className="w-[18px] h-[18px] text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M9 19v-6a2 2 0 00-2-2H5a2 2 0 00-2 2v6a2 2 0 002 2h2a2 2 0 002-2zm0 0V9a2 2 0 012-2h2a2 2 0 012 2v10m-6 0a2 2 0 002 2h2a2 2 0 002-2m0 0V5a2 2 0 012-2h2a2 2 0 012 2v14a2 2 0 01-2 2h-2a2 2 0 01-2-2z" />
            </svg>
          </div>
          <div>
            <p className="text-white font-semibold text-sm leading-tight">SEO Monitor</p>
            <p className="text-xs" style={{ color: 'rgba(255,255,255,0.3)' }}>监控后台</p>
          </div>
        </div>
      </div>

      {/* ── Nav ── */}
      <nav className="flex-1 px-3 pb-3 overflow-y-auto space-y-0.5" style={{ scrollbarWidth: 'none' }}>
        {allItems.map(item => {
          if (item.children) {
            const isParentActive = pathname === item.href
            const hasActiveChild = item.children.some(c => pathname.startsWith(c.href))
            return (
              <div key={item.href}>
                <Link
                  href={item.href}
                  className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-all duration-150 ${
                    isParentActive
                      ? 'bg-green-600 text-white'
                      : hasActiveChild
                      ? 'text-white/80 hover:bg-white/5'
                      : 'text-white/45 hover:bg-white/8 hover:text-white/90'
                  }`}
                >
                  {item.icon}
                  {item.label}
                </Link>
                <div className="ml-3 mt-0.5 space-y-0.5">
                  {item.children.map(child => {
                    const isChildActive = pathname.startsWith(child.href)
                    return (
                      <Link
                        key={child.href}
                        href={child.href}
                        className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm font-medium transition-all duration-150 ${
                          isChildActive
                            ? 'bg-green-600 text-white'
                            : 'text-white/40 hover:bg-white/8 hover:text-white/80'
                        }`}
                      >
                        {child.icon}
                        {child.label}
                      </Link>
                    )
                  })}
                </div>
              </div>
            )
          }

          const isActive = item.href === '/'
            ? pathname === '/'
            : pathname.startsWith(item.href)
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-all duration-150 ${
                isActive
                  ? 'bg-green-600 text-white'
                  : 'text-white/45 hover:bg-white/8 hover:text-white/90'
              }`}
            >
              {item.icon}
              {item.label}
            </Link>
          )
        })}
      </nav>

      {/* ── Logout ── */}
      <div className="px-3 py-4" style={{ borderTop: '1px solid rgba(255,255,255,0.06)' }}>
        <button
          onClick={handleLogout}
          className="w-full flex items-center gap-3 px-3 py-2 rounded-lg text-sm font-medium transition-all duration-150"
          style={{ color: 'rgba(255,255,255,0.35)' }}
          onMouseEnter={e => {
            (e.currentTarget as HTMLElement).style.background = 'rgba(239,68,68,0.1)'
            ;(e.currentTarget as HTMLElement).style.color = '#fca5a5'
          }}
          onMouseLeave={e => {
            (e.currentTarget as HTMLElement).style.background = 'transparent'
            ;(e.currentTarget as HTMLElement).style.color = 'rgba(255,255,255,0.35)'
          }}
        >
          <svg className="w-[18px] h-[18px]" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.8}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M17 16l4-4m0 0l-4-4m4 4H7m6 4v1a3 3 0 01-3 3H6a3 3 0 01-3-3V7a3 3 0 013-3h4a3 3 0 013 3v1" />
          </svg>
          退出登录
        </button>
      </div>
    </aside>
  )
}
